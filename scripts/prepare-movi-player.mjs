import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const source = path.join(root, "node_modules/movi-player/dist/element.js");
const targetDir = path.join(root, "public/vendor/movi-player");
const target = path.join(targetDir, "element.js");
const versionFile = path.join(root, "lib/movi/movi-player-asset.generated.ts");

const tabindexBug =
  /this\.hasAttribute\("tabindex"\)\s*\|\|\s*this\.setAttribute\("tabindex",\s*"0"\)/g;

// movi syncs clock to audio for gaps ≤200ms after seek, which leaves video
// frozen on the pre-seek frame while audio/time advance. force video-first.
const postSeekAudioFirstSync =
  /const t3 = 0\.2;\s*let n3 = A2, b3 = false;\s*if \(this\.pendingAudioPackets\.length > 0\)/;

// interactive AudioContext keeps ~50–150ms scheduled; treating <100ms as
// "starving" at non-1x rates drops non-keyframes and corrupts GOP chains.
const demuxAudioStarving = /!this\.disableAudio && c2 < 0\.1/g;

// stall detector fires when audio buffer dips below 50ms even during normal
// decode catch-up; require a thinner cushion before counting as stalled.
const stallAudioLow = /this\.audioRenderer\.getBufferedDuration\(\) < 0\.05/g;

// isAudioStarved() bails out once buffer exceeds 100ms; lower bar reduces
// false starvation signals during steady interactive playback.
const audioStarvedHasBuffer =
  /if \(this\.getBufferedDuration\(\) > 0\.1\) return false;/g;

if (!fs.existsSync(source)) {
  console.warn("[prepare-movi-player] movi-player not installed, skipping");
  process.exit(0);
}

let code = fs.readFileSync(source, "utf8");
let patches = 0;

if (tabindexBug.test(code)) {
  tabindexBug.lastIndex = 0;
  code = code.replace(tabindexBug, "void 0");
  patches += 1;
}

if (postSeekAudioFirstSync.test(code)) {
  postSeekAudioFirstSync.lastIndex = 0;
  code = code.replace(
    postSeekAudioFirstSync,
    "const t3 = 0; let n3 = A2, b3 = false; if (this.pendingAudioPackets.length > 0)",
  );
  patches += 1;
} else {
  console.warn(
    "[prepare-movi-player] post-seek audio-first sync pattern not found — movi version may have changed",
  );
}

if (demuxAudioStarving.test(code)) {
  demuxAudioStarving.lastIndex = 0;
  code = code.replace(demuxAudioStarving, "!this.disableAudio && c2 < 0.05");
  patches += 1;
} else {
  console.warn(
    "[prepare-movi-player] demux audio-starving pattern not found — movi version may have changed",
  );
}

if (stallAudioLow.test(code)) {
  stallAudioLow.lastIndex = 0;
  code = code.replace(
    stallAudioLow,
    "this.audioRenderer.getBufferedDuration() < 0.02",
  );
  patches += 1;
} else {
  console.warn(
    "[prepare-movi-player] stall audio-low pattern not found — movi version may have changed",
  );
}

if (audioStarvedHasBuffer.test(code)) {
  audioStarvedHasBuffer.lastIndex = 0;
  code = code.replace(
    audioStarvedHasBuffer,
    "if (this.getBufferedDuration() > 0.05) return false;",
  );
  patches += 1;
} else {
  console.warn(
    "[prepare-movi-player] isAudioStarved buffer pattern not found — movi version may have changed",
  );
}

fs.mkdirSync(targetDir, { recursive: true });
fs.writeFileSync(target, code);

// Content hash lets /vendor/movi-player be served with immutable cache headers
// while still busting caches on movi upgrades or patch changes.
const assetVersion = crypto
  .createHash("sha256")
  .update(code)
  .digest("hex")
  .slice(0, 8);
fs.writeFileSync(
  versionFile,
  `// Generated by scripts/prepare-movi-player.mjs — do not edit.\nexport const MOVI_PLAYER_ASSET_VERSION = "${assetVersion}";\n`,
);

console.log(
  `[prepare-movi-player] wrote ${path.relative(root, target)} (${patches} patches, v=${assetVersion})`,
);
